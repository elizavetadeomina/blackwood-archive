document.addEventListener("DOMContentLoaded", () => {
    initMapPins();
    initNewspapers();
    initSmoothScroll();
    initModalClose();
});

// ============================================================
// КАРТА: клики по меткам
// ============================================================
function initMapPins() {
    const infoBox = document.getElementById("location-info");

    document.querySelectorAll(".map-pin").forEach((pin) => {
        pin.addEventListener("click", () => {
            const locId = pin.dataset.location;
            const loc = locations[locId];

            if (loc) {
                infoBox.innerHTML = `
                    <h3>${loc.title}</h3>
                    <p>${loc.description}</p>
                    <p class="coords">💭 ${loc.note}</p>
                `;

                // Прокрутка к инфобоксу
                infoBox.scrollIntoView({ behavior: "smooth", block: "nearest" });
            }
        });
    });
}

// ============================================================
// ГАЗЕТЫ: открытие полной статьи
// ============================================================
function initNewspapers() {
    document.querySelectorAll(".newspaper").forEach((article) => {
        article.addEventListener("click", () => {
            const articleId = article.dataset.article;
            const data = articles[articleId];

            if (data) {
                openArticle(data);
            }
        });
    });
}

function openArticle(data) {
    const modal = document.getElementById("modal");
    const body = document.getElementById("modal-body");

    const paragraphs = data.body.map((p) => `<p>${p}</p>`).join("");

    body.innerHTML = `
        <div class="modal-article">
            <div class="article-header">
                <div class="article-date">${data.date}</div>
                <div class="article-title">${data.title}</div>
            </div>
            <div class="article-body">
                ${paragraphs}
            </div>
            <div class="article-signature">— ${data.signature}</div>
        </div>
    `;

    modal.classList.add("active");
    document.body.style.overflow = "hidden";
}

function closeModal() {
    const modal = document.getElementById("modal");
    modal.classList.remove("active");
    document.body.style.overflow = "";
}

function initModalClose() {
    const modal = document.getElementById("modal");

    // Клик по фону — закрыть
    modal.addEventListener("click", (e) => {
        if (e.target === modal) {
            closeModal();
        }
    });

    // Escape — закрыть
    document.addEventListener("keydown", (e) => {
        if (e.key === "Escape") {
            closeModal();
        }
    });
}

// ============================================================
// ПЛАВНАЯ ПРОКРУТКА ПО НАВИГАЦИИ
// ============================================================
function initSmoothScroll() {
    document.querySelectorAll("nav a").forEach((link) => {
        link.addEventListener("click", (e) => {
            e.preventDefault();
            const target = document.querySelector(link.getAttribute("href"));
            if (target) {
                const offset = 80;
                const top = target.getBoundingClientRect().top + window.pageYOffset - offset;
                window.scrollTo({ top, behavior: "smooth" });
            }
        });
    });
}