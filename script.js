document.addEventListener("DOMContentLoaded", () => {
    initMapPins();
    initNewspapers();
    initSmoothScroll();
    initModalClose();
});

// ============================================================
// КАРТА — с фото
// ============================================================
function initMapPins() {
    const infoBox = document.getElementById("location-info");
    if (!infoBox) return;

    document.querySelectorAll(".map-pin").forEach((pin) => {
        pin.addEventListener("click", () => {
            const locId = pin.dataset.location;
            const loc = locations[locId];

            if (loc) {
                // Фото (если есть)
                let photoHtml = "";
                if (loc.photo) {
                    photoHtml = `
                        <div class="location-photo">
                            <img src="${loc.photo}" alt="${loc.title}"
                                 onerror="this.parentElement.style.display='none'">
                        </div>
                    `;
                }

                infoBox.innerHTML = `
                    ${photoHtml}
                    <h3>${loc.title}</h3>
                    <p>${loc.description}</p>
                    <p class="coords">💭 ${loc.note}</p>
                `;
                infoBox.scrollIntoView({ behavior: "smooth", block: "nearest" });
            }
        });
    });
}

// ============================================================
// ГАЗЕТЫ
// ============================================================
function initNewspapers() {
    document.querySelectorAll(".newspaper").forEach((article) => {
        article.addEventListener("click", () => {
            const articleId = article.dataset.article;
            const data = articles[articleId];
            if (data) {
                openArticle(data);
            } else {
                alert("Статья не найдена: " + articleId);
            }
        });
    });
}

function openArticle(data) {
    const modal = document.getElementById("modal");
    const body = document.getElementById("modal-body");

    let photoHtml = "";
    if (data.photo) {
        photoHtml = `
            <div class="article-photo">
                <img src="${data.photo}" alt="${data.title}"
                     onerror="this.parentElement.style.display='none'">
            </div>
        `;
    }

    const paragraphs = data.body.map((p) => `<p>${p}</p>`).join("");

    body.innerHTML = `
        <div class="modal-article">
            <div class="article-header">
                <div class="article-date">${data.date}</div>
                <div class="article-title">${data.title}</div>
            </div>
            ${photoHtml}
            <div class="article-body">${paragraphs}</div>
            <div class="article-signature">— ${data.signature}</div>
        </div>
    `;

    modal.classList.add("active");
    document.body.style.overflow = "hidden";
}

function closeModal() {
    const modal = document.getElementById("modal");
    modal.classList.remove("active");
    document.body.style.overflow = "";
}

function initModalClose() {
    const modal = document.getElementById("modal");
    if (!modal) return;

    modal.addEventListener("click", (e) => {
        if (e.target === modal) closeModal();
    });

    document.addEventListener("keydown", (e) => {
        if (e.key === "Escape") closeModal();
    });
}

// ============================================================
// ПЛАВНАЯ ПРОКРУТКА
// ============================================================
function initSmoothScroll() {
    document.querySelectorAll('.main-nav a[href^="#"]').forEach((link) => {
        link.addEventListener("click", (e) => {
            e.preventDefault();
            const target = document.querySelector(link.getAttribute("href"));
            if (target) {
                const offset = 80;
                const top = target.getBoundingClientRect().top
                    + window.pageYOffset - offset;
                window.scrollTo({ top, behavior: "smooth" });
            }
        });
    });
}
